'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');
const { createSharedFirebaseBackend } = require('../tests/shared-firebase-backend.cjs');
const root = path.resolve(__dirname, '..');
const report = path.resolve(process.argv[2] || path.join(root, '../calendar-recurrence-results'));
(async () => {
  fs.mkdirSync(report, { recursive: true });
  const backend = createSharedFirebaseBackend(2), errors = [];
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1450, height: 1100 }, timezoneId: 'America/New_York' });
    await backend.bind(context);
    await context.addInitScript(() => { const OriginalDate = Date, stamp = OriginalDate.parse('2026-11-09T20:00:00Z'); window.Date = class extends OriginalDate { constructor(...args) { super(...(args.length ? args : [stamp])); } static now() { return stamp; } }; });
    await context.route(/^https?:\/\//, route => route.fulfill({ status: 200, contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: 'null' }));
    const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
    await page.waitForFunction(() => document.documentElement.dataset.appReady === 'true');
    await page.fill('#login-email', 'vincenzo.brogna@students.pittstonarea.com');
    await page.click('#btn-go-login'); await page.fill('#login-code', 'P1'); await page.click('#btn-login');
    await page.waitForFunction(() => ChatApp.calendarState?.ready && ChatApp.calendarState?.connected && ChatApp.calendarState?.repeatingReady);
    await page.evaluate(() => ChatApp.closeToast?.('manual'));
    await page.evaluate(() => ChatApp.showCalendarPage('2026-11-10'));
    const form = page.locator('.calendar-editor-new');
    await form.locator('textarea').fill('Biology review every Tuesday');
    await form.locator('.calendar-repeat-label').click();
    assert.equal(await form.locator('.calendar-repeat-checkbox').isChecked(), true);
    await form.locator('.calendar-editor-save').click();
    await page.waitForFunction(() => Object.keys(ChatApp.calendarState.repeating).length === 1);
    await page.waitForFunction(() => !document.querySelector('.calendar-repeat-checkbox').checked);
    const seriesId = await page.evaluate(() => Object.keys(ChatApp.calendarState.repeating)[0]);
    assert.equal(Object.keys(backend.get('calendar/years/2026')).length, 3);
    const row = page.locator(`.calendar-repeat-row[data-series-id="${seriesId}"]`);
    await row.locator('.calendar-repeat-open').click();
    assert.equal(await page.locator('.calendar-repeat-details .calendar-note-item').count(), 3);
    await row.locator('.calendar-repeat-label').click();
    await page.waitForFunction(id => !ChatApp.calendarState.repeating[id].enabled, seriesId);
    assert.equal(Object.keys(backend.get('calendar/years/2026')).length, 3);
    await row.getByRole('button', { name: 'Edit', exact: true }).click();
    await row.locator('textarea').fill('Revised weekly review');
    await row.getByRole('button', { name: 'Save', exact: true }).click();
    await page.waitForFunction(id => ChatApp.calendarState.repeating[id].text === 'Revised weekly review', seriesId);
    assert.equal(await page.locator('.calendar-repeat-details .calendar-note-bubble').first().textContent(), 'Revised weekly review');
    await page.locator('.calendar-repeat-details .calendar-editor-delete').nth(1).click();
    await page.waitForFunction(() => document.querySelectorAll('.calendar-repeat-details .calendar-note-item').length === 2);
    await page.evaluate(() => ChatApp.materializeCalendarRepeating());
    assert.equal(backend.get('calendar/years/2026/2026-11-17'), null);
    await page.evaluate(async () => { for (let i = 0; i < 7; i++) await ChatApp.saveCalendarNote('2026-11-10', null, `Another note ${i} with long text that should show a tooltip and remain accessible in the month grid without opening a day.`); });
    const preview = page.locator('.calendar-day[data-date="2026-11-10"] .calendar-note-preview');
    assert.equal(await preview.count(), 8);
    await page.evaluate(() => { ChatApp.messagesEl.scrollTop = 0; });
    await preview.nth(1).hover();
    await page.locator('#sidebar-tooltip.is-visible').waitFor();
    assert.ok((await page.locator('#sidebar-tooltip').textContent()).includes('without opening a day.'));
    await page.screenshot({ path: path.join(report, 'calendar-month.png') });
    const widths = await page.evaluate(() => { const width = selector => document.querySelector(selector).getBoundingClientRect().width; return [width('.calendar-month-grid-card'), width('.calendar-notes-section'), width('.calendar-repeating-section')]; });
    assert.ok(Math.max(...widths) - Math.min(...widths) < 2, `forms align with calendar: ${widths}`);
    await row.scrollIntoViewIfNeeded();
    await page.locator('#sidebar-tooltip.is-visible').waitFor({ state: 'hidden' });
    await page.screenshot({ path: path.join(report, 'calendar-repeating.png') });
    await form.locator('textarea').fill(' REVISED    weekly REVIEW ');
    await form.locator('.calendar-editor-save').click();
    await page.waitForFunction(() => document.querySelector('.calendar-editor-new .calendar-editor-status')?.textContent.includes('same text'));
    assert.equal(Object.keys(backend.get('calendar/years/2026/2026-11-10')).length, 8);
    await row.locator('.calendar-repeat-label').click();
    await page.waitForFunction(id => ChatApp.calendarState.repeating[id].enabled, seriesId);
    await row.getByRole('button', { name: 'Delete', exact: true }).click();
    await page.waitForFunction(() => Object.keys(ChatApp.calendarState.repeating).length === 0);
    assert.equal(Object.values(backend.get('calendar/years/2026/2026-11-10')).some(note => note.seriesId), false);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => { ChatApp.messagesEl.scrollTop = 0; ChatApp.closeMobileDrawers?.(); });
    await page.waitForTimeout(350);
    await page.screenshot({ path: path.join(report, 'calendar-mobile.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(report, 'result.json'), JSON.stringify({ ok: true, errors, widths }, null, 2));
    console.log('Calendar recurrence browser checks passed; screenshots: ' + report);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
